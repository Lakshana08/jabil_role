"""Assistant Agent - one confirm-before-change entry point for chat channels that have no
routing of their own (the Teams bot). Joule picks an agent through its
scenario descriptions; a plain chat channel just sends text, so this agent
picks the agent instead and hands the request over unchanged:

  - the follow-up prompts our own buttons send ("Generate a ... report ...",
    "Show ..., rows 21-40") are routed by rule, no LLM call;
  - anything else is classified by one short AI Core call
    (query / report / action / none).

Changes to SAP data are never applied straight from chat text - the same
confirm-before-change flow as Joule (action_agent.prepare_change /
resolve_change): a change request is only *prepared*, saved server-side under
a one-time code (services/pending_changes.py), and executed only when
"Confirm change <code>" comes back. The Teams bot sends the asking user in the
message metadata (requested_by), so only that user can confirm or cancel.
"""

import logging
import re

from a2a.server.agent_execution import AgentExecutor, RequestContext
from a2a.server.events import EventQueue
from a2a.types import AgentSkill

from app.a2a_agents.action_agent import parse_decision, prepare_change, resolve_change
from app.a2a_agents.common import (
    REPORT_REQUEST_RE,
    build_agent_card,
    emit_response,
    get_structured_input,
    keep_markdown_tables,
    requester_from,
)
from app.a2a_agents.query_agent import QueryAgentExecutor
from app.a2a_agents.report_agent import ReportAgentExecutor
from app.core_capabilities.paging import skip_from_text
from app.services.ai_core import AgentBusyError, classify

logger = logging.getLogger(__name__)

SKILL = AgentSkill(
    id="smart_material_assistant",
    name="Smart Material Assistant",
    description=(
        "Assistant for S/4HANA material data. Answers material master, stock, "
        "production order questions, and generates CSV/Excel/PDF reports - routing each "
        "plain-text question to the right specialist agent. Requests to change SAP data are "
        "only prepared and saved under a one-time code; they are executed only when "
        "'Confirm change <code>' is sent back (or cancelled with 'Cancel change <code>')."
    ),
    tags=["s4hana", "material", "production-order", "report", "action", "confirmation"],
    examples=[
        "Show production orders for plant 1710",
        "What's the stock for material TG20?",
        "Generate a production order report at plant 1710 in CSV format",
    ],
    input_modes=["text/plain", "application/json"],
    output_modes=["application/json", "text/plain"],
)

HELP_TEXT = (
    "I answer questions about SAP material data, and can make changes after you confirm them. Try:\n\n"
    "- Any over-issued materials in storage location A301?\n"
    "- Which work orders have missing parts?\n"
    "- Show the 10 oldest aged materials\n"
    "- Generate a component shortage report for order 121060001 in Excel format\n"
    "- Update the gross weight of material ACEP23701 to 0.05 KG"
)

_ROUTE_PROMPT = """Route the user's message to exactly one SAP material assistant. Reply with ONE word only:
query  - looks up or counts S/4HANA data: material master / plant / valuation / BOM data, stock, \
inventory value, aged inventory, over-control / over-issued, non-controlled or issuable material, \
putaway, work-order components, 14C issuance, order status, production orders, missing parts and \
shortages, or "how many ... are there".
report - asks to generate, export or download a report or file (CSV, Excel, PDF).
action - asks to create, change, update, set or delete anything.
none   - greetings, thanks, help requests, or anything unrelated to SAP material data."""

def _route_by_rule(text: str) -> str | None:
    """Prompts generated by our own buttons, routed without an LLM call. Only
    the Query agent pages, so every "..., rows 21-40" follow-up goes there."""
    if parse_decision(text):
        return "decision"
    if REPORT_REQUEST_RE.match(text):
        return "report"
    if skip_from_text(text) is not None:
        return "query"
    return None


def _route_structured(args: dict) -> str | None:
    if "report_type" in args:
        return "report"
    if "query_type" in args or "material" in args or "product" in args:
        return "query"
    return None


def build_assistant_agent_card(base_url: str):
    return build_agent_card(
        name="Smart Material Assistant",
        description=(
            "Entry point that routes each question to the Material Query or Report agent, "
            "and turns change requests into confirm-first proposals for the Action agent - for chat "
            "channels (e.g. Microsoft Teams) with no routing of their own."
        ),
        skill=SKILL,
        base_url=base_url,
    )


class AssistantAgentExecutor(AgentExecutor):
    def __init__(self) -> None:
        self._agents: dict[str, AgentExecutor] = {
            "query": QueryAgentExecutor(),
            "report": ReportAgentExecutor(),
        }

    async def execute(self, context: RequestContext, event_queue: EventQueue) -> None:
        # The Teams bot renders Markdown tables as real card tables - keep them.
        keep_markdown_tables.set(True)
        args = get_structured_input(context)
        if args is not None:
            route = _route_structured(args)
        else:
            text = context.get_user_input().strip()
            if not text:
                await emit_response(event_queue, context, HELP_TEXT)
                return
            route = _route_by_rule(text)
            if route is None:
                try:
                    route = await classify(_ROUTE_PROMPT, text)
                except AgentBusyError as exc:
                    await emit_response(event_queue, context, exc.user_message, {"error": "busy"})
                    return

        if route in self._agents:
            # Same request, same event queue - the specialist answers exactly
            # as if it had been called directly (paging, report links, notes).
            await self._agents[route].execute(context, event_queue)
        elif route == "action":
            # Prepared only - saved under a one-time code for Confirm / Cancel.
            reply, data = await prepare_change(context.get_user_input().strip(), requester_from(context))
            await emit_response(event_queue, context, reply, data)
        elif route == "decision":
            reply, data = await resolve_change(*parse_decision(context.get_user_input()), requester_from(context))
            await emit_response(event_queue, context, reply, data)
        elif route == "none":
            await emit_response(event_queue, context, HELP_TEXT)
        else:
            # AI Core disabled/failed, or an unexpected label.
            await emit_response(
                event_queue,
                context,
                "I couldn't work out what you're asking right now. " + HELP_TEXT,
                {"error": "routing_failed"},
            )

    async def cancel(self, context: RequestContext, event_queue: EventQueue) -> None:
        return None
