def _structured_filters(args: dict) -> dict:
    """filters from a structured call: an explicit "filters" object, plus any
    filter given at the top level (old callers send material/plant/product/...)."""
    filters = dict(args.get("filters") or {})
    for name in list(FILTER_NAMES) + list(FILTER_ALIASES):
        if args.get(name) and name not in filters:
            filters[name] = args[name]
    return filters


def _run_structured_query(args: dict) -> tuple[dict, str]:
    """Deterministic dispatch for structured JSON callers - no LLM involved."""
    query_type = args.get("query_type", "material_stock")
    filters = _structured_filters(args)
    conditions = args.get("conditions") or None
    if args.get("count_only"):
        result = count_records(query_type, filters, conditions)
        return result, f"Total {result['label']} count: {result['count']}."
    result = query_source(
        query_type,
        filters,
        conditions,
        args.get("order_by"),
        skip=int(args.get("skip") or 0),
        top=int(args.get("top") or QUERY_ROW_LIMIT),
    )
    scope = describe_scope(result["filters"], result["conditions"])
    if not result["results"]:
        return result, f"No {result['label']} records found{scope}."
    summary = f"Found {result['count']} {result['label']} record(s){scope}."
    if result["has_more"]:
        summary += f" Showing rows {result['skip'] + 1}-{result['skip'] + result['returned']}; pass skip to get more."
    return result, summary


class PlannerAgentExecutor(AgentExecutor):
    async def execute(self, context: RequestContext, event_queue: EventQueue) -> None:
        args = get_structured_input(context)

        if args is not None:
            query_type = args.get("query_type", "material_stock")
            if query_type not in BY_NAME:
                await emit_response(
                    event_queue,
                    context,
                    f"Unknown query_type '{query_type}', expected one of {', '.join(BY_NAME)}.",
                    {"error": "unknown_query_type"},
                )
                return
            try:
                result, summary = await asyncio.to_thread(_run_structured_query, args)
            except S4SchemaError as exc:
                await emit_response(event_queue, context, str(exc), {"error": "invalid_request"})
                return
            except S4ClientError as exc:
                await emit_response(event_queue, context, f"S/4HANA error: {exc}", {"error": "s4_error"})
                return
            await emit_response(event_queue, context, summary, _add_report_prompts(result))
            return

        # Free text - let the AI Core tool-calling agent decide what to call.
        text = context.get_user_input()
        if REPORT_REQUEST_RE.match(text):
            # Reports are the Report agent's job only - answered here without an LLM call.
            await emit_response(event_queue, context, REPORT_ELSEWHERE, {"error": "report_not_supported"})
            return
        requested_skip.set(skip_from_text(text))
        agent_result = await run_agent(_AGENT_SYSTEM_PROMPT, _TOOLS, text)
        if agent_result is None:
            await emit_response(
                event_queue,
                context,
                "I couldn't process that request right now (AI Core unavailable).",
                {"error": "ai_core_unavailable"},
            )
            return

        answer, tool_outputs = agent_result
        data = tool_data(tool_outputs)
        await emit_response(event_queue, context, answer, data)

    async def cancel(self, context: RequestContext, event_queue: EventQueue) -> None:
        # Single-shot synchronous lookups - nothing runs long enough to cancel mid-flight.
        return None
