# Free-text tools fetch one PAGE_SIZE page per call, never query.py's full
# QUERY_ROW_LIMIT (200) - 200 full-width rows fed into the LLM's tool-calling
# loop blew its context window (confirmed live: 200 raw production order rows
# alone hit 141k tokens, over the model's 128k limit). count stays the real
# S/4 total, and the rest is reachable page by page via next_page_prompt.


def _add_report_prompts(result: dict) -> dict:
    """Pre-computes the exact free-text prompts a caller sends to turn this
    result into a downloadable report, or to fetch the next page - plain
    strings, so a Joule button needs only a flat property lookup (its SpEL
    proved unable to evaluate branching logic reliably)."""
    label = result.get("label") or "data"
    scope = describe_scope(result.get("filters"), result.get("conditions"), result.get("order_by"))
    article = "an" if label[0].lower() in "aeiou" else "a"
    base = f"Generate {article} {label} report{scope}"
    subject = f"{label} data{scope}"
    return {
        **result,
        "report_prompt_csv": f"{base} in CSV format",
        "report_prompt_excel": f"{base} in Excel format",
        "report_prompt_pdf": f"{base} in PDF format",
        "next_page_prompt": None if result.get("count_only") else next_page_prompt(subject, result),
    }


REPORT_ELSEWHERE = (
    "Reports are generated by the Report agent, not the Planner. Please ask the Report agent "
    "(the Report tab), or use the report option under a Planner answer."
)


def _skip(skip: int) -> int:
    """The LLM's skip, or - if it passed 0 - the page parsed from the user's
    own "rows 21-40" text, so a next-page click always lands on that page."""
    return skip or requested_skip.get() or 0


def _tool_error(source: str, exc: Exception) -> dict:
    # Handed back to the LLM instead of aborting the turn, so it can fix the
    # filter/field it got wrong and call again, or explain the problem.
    return {"error": str(exc), "query_type": source}


@tool
def query_data(
    source: str,
    filters: dict[str, str] | None = None,
    conditions: list[str] | None = None,
    order_by: str = "",
    skip: int = 0,
) -> dict:
    """Read rows from one S/4HANA data source (see the source list in your instructions).
    filters: simple filters the source supports, e.g. {"material": "ACPE21680", "storage_location": "A201"};
    a value may be comma-separated for "any of". conditions: extra conditions on any field of the
    source, e.g. ["AgingDays > 90", "ShortageQty > 0"] (operators = != > >= < <= contains startswith;
    dates as YYYY-MM-DD). order_by: e.g. "AgingDays desc". Returns one page of rows plus the true
    total count; skip selects the page ("rows 21-40" -> skip=20)."""
    try:
        result = query_source(source, filters, conditions, order_by or None, skip=_skip(skip), top=PAGE_SIZE)
    except (S4ClientError, ValueError) as exc:
        return _tool_error(source, exc)
    return _add_report_prompts(humanize_odata_dates(result))


@tool
def count_data(source: str, filters: dict[str, str] | None = None, conditions: list[str] | None = None) -> dict:
    """How many rows of a data source match the filters/conditions - the real total from S/4HANA.
    Use for "how many ..." questions instead of query_data."""
    try:
        return _add_report_prompts(count_records(source, filters, conditions))
    except (S4ClientError, ValueError) as exc:
        return _tool_error(source, exc)


_TOOLS = [query_data, count_data]

